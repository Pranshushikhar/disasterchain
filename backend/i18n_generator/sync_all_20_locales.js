async function syncAllLocales() {
  console.log('Synchronizing Disaster Academy, Offline Emergency Mode, and Voice translations across all 20 languages...\n');

  // 1. First, load en.json
  const enPath = path.join(localesDir, 'en.json');
  const enData = JSON.parse(fs.readFileSync(enPath, 'utf8'));

  // Ensure en.json has nav.academy, academy, and offline
  enData.nav = enData.nav || {};
  enData.nav.academy = "Disaster Academy";
  enData.academy = academyTranslations.en;
  enData.offline = offlineTranslations.en;
  fs.writeFileSync(enPath, JSON.stringify(enData, null, 2) + '\n', 'utf8');
  console.log('✅ Updated en.json');

  // 2. Process all other 19 languages
  for (const lang of SUPPORTED_LANGS) {
    if (lang === 'en') continue;

    const filePath = path.join(localesDir, `${lang}.json`);
    if (!fs.existsSync(filePath)) {
      console.warn(`File not found: ${filePath}`);
      continue;
    }

    const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));

    // Inject voice keys if missing or empty
    if (voiceTranslations[lang]) {
      data.voice = data.voice || {};
      for (const [k, v] of Object.entries(voiceTranslations[lang])) {
        if (!data.voice[k]) {
          data.voice[k] = v;
        }
      }
    }

    // Inject nav.academy
    data.nav = data.nav || {};
    data.nav.academy = navAcademyTranslations[lang] || "Disaster Academy";

    // Inject academy
    data.academy = academyTranslations[lang] || academyTranslations.en;

    // Inject offline
    data.offline = offlineTranslations[lang] || offlineTranslations.en;

    // Deep reconcile with en.json to ensure 100% key parity
    function deepReconcile(source, target, langCode) {
      for (const key of Object.keys(source)) {
        if (typeof source[key] === 'object' && source[key] !== null && !Array.isArray(source[key])) {
          target[key] = target[key] || {};
          deepReconcile(source[key], target[key], langCode);
        } else {
          if (target[key] === undefined || target[key] === null || target[key] === '') {
            // If target missing, use source value
            target[key] = source[key];
          }
        }
      }
    }

    deepReconcile(enData, data, lang);

    fs.writeFileSync(filePath, JSON.stringify(data, null, 2) + '\n', 'utf8');
    console.log(`✅ Synchronized and reconciled ${lang}.json`);
  }

  console.log('\n🎉 ALL 20 LOCALES SYNCHRONIZED SUCCESSFULLY!');
}

syncAllLocales();
