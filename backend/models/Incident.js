const mongoose = require('mongoose');

const incidentSchema = new mongoose.Schema({
  incidentId: {
    type: String,
    required: true,
    unique: true,
    default: () => `INC-${Math.floor(1000 + Math.random() * 9000)}`,
  },
  title: {
    type: String,
    required: [true, 'Please add incident title'],
    trim: true,
  },
  type: {
    type: String,
    required: [true, 'Please specify hazard/disaster type'],
    enum: [
      'Blocked emergency exit',
      'Fire hazard',
      'Flooding',
      'Damaged building',
      'Damaged electrical equipment',
      'Fallen tree',
      'Unsafe construction area',
      'Earthquake Damage',
      'Gas Leak',
      'Other',
    ],
  },
  description: {
    type: String,
    required: [true, 'Please provide detailed description of the incident'],
  },
  severity: {
    type: String,
    enum: ['Low', 'Medium', 'High', 'Critical'],
    default: 'Medium',
  },
  location: {
    type: String,
    required: [true, 'Please provide location of incident'],
  },
  latitude: {
    type: Number,
    default: null,
  },
  longitude: {
    type: Number,
    default: null,
  },
  imageUrl: {
    type: String,
    default: '',
  },
  reportedBy: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'User',
  },
  reporterName: {
    type: String,
    default: 'Anonymous Student',
  },
  status: {
    type: String,
    enum: [
      'Pending',
      'Under Review',
      'Resolved',
      'Rejected',
      'Received',
      'Under Verification',
      'Community Corroborated',
      'Officially Verified',
      'Disputed',
      'Duplicate / Merged',
    ],
    default: 'Received',
  },
  verificationStatus: {
    type: String,
    enum: [
      'Received',
      'Under Verification',
      'Community Corroborated',
      'Officially Verified',
      'Disputed',
      'Rejected',
      'Duplicate / Merged',
    ],
    default: 'Received',
  },
  trustScore: {
    type: Number,
    min: 0,
    max: 100,
    default: 35,
  },
  trustLevel: {
    type: String,
    enum: [
      'Insufficient supporting evidence',
      'Low confidence',
      'Moderate confidence',
      'High confidence',
      'Strong supporting evidence',
    ],
    default: 'Low confidence',
  },
  trustScoreBreakdown: {
    evidenceQuality: { score: Number, max: Number, reason: String },
    mediaAuthenticity: { score: Number, max: Number, reason: String },
    locationConsistency: { score: Number, max: Number, reason: String },
    timestampConsistency: { score: Number, max: Number, reason: String },
    witnessConfirmations: { score: Number, max: Number, reason: String },
    communityCorroboration: { score: Number, max: Number, reason: String },
    officialCorroboration: { score: Number, max: Number, reason: String },
    duplicateContradiction: { score: Number, max: Number, reason: String },
  },
  aiEvidenceSummary: {
    narrative: { type: String, default: '' },
    concerns: [{ type: String }],
    supportingObservations: [{ type: String }],
    recommendedAction: { type: String, default: 'Awaiting secondary community corroboration.' },
    missingEvidence: [{ type: String }],
    modelUsed: { type: String, default: 'DisasterChain Evidence Synthesis Engine v2.4' },
    analyzedAt: { type: Date, default: Date.now },
  },
  witnessStats: {
    confirmedCount: { type: Number, default: 0 },
    disputedCount: { type: Number, default: 0 },
    lastConfirmedAt: { type: Date },
  },
  duplicateInfo: {
    isDuplicate: { type: Boolean, default: false },
    mergedIntoIncidentId: { type: String, default: null },
    mergedIncidents: [{ type: String }],
    duplicateMatchScore: { type: Number, default: 0 },
    matchReasons: [{ type: String }],
  },
  mediaAnalysis: [
    {
      url: String,
      mediaType: { type: String, default: 'image' },
      isAiGeneratedProbability: { type: Number, default: 0 },
      aiDetectionStatus: {
        type: String,
        enum: ['authentic', 'uncertain', 'likely_synthetic', 'service_unavailable'],
        default: 'authentic',
      },
      confidence: { type: Number, default: 0.85 },
      manipulationIndicators: {
        editingDetected: { type: Boolean, default: false },
        inconsistencies: [{ type: String }],
        exifData: { type: mongoose.Schema.Types.Mixed, default: {} },
        exifStatus: {
          type: String,
          enum: ['verified', 'missing', 'suspicious', 'inconsistent'],
          default: 'missing',
        },
        perceptualHash: { type: String, default: '' },
        isDuplicateMedia: { type: Boolean, default: false },
        matchedIncidentId: { type: String, default: null },
      },
      relevance: {
        isRelevant: { type: Boolean, default: true },
        detectedHazards: [{ type: String }],
        confidence: { type: Number, default: 0.8 },
        locationConsistencyScore: { type: Number, default: 80 },
        notes: { type: String, default: '' },
      },
      videoSummary: {
        analyzedFrames: { type: Number, default: 0 },
        keyframes: [{ type: String }],
        frameDuplicateDetected: { type: Boolean, default: false },
        visualSummary: { type: String, default: '' },
      },
      modelUsed: { type: String, default: 'DisasterChain Visual Forensics v2.1' },
      analyzedAt: { type: Date, default: Date.now },
    },
  ],
  auditLog: [
    {
      adminId: { type: String },
      adminName: { type: String },
      action: {
        type: String,
        enum: [
          'REPORT_CREATED',
          'VERIFY',
          'REQUEST_EVIDENCE',
          'MARK_DISPUTED',
          'REJECT',
          'MERGE',
          'ESCALATE',
          'ADD_NOTE',
          'REOPEN',
          'WITNESS_CONFIRMED',
          'WITNESS_DISPUTED',
        ],
      },
      reason: { type: String, default: '' },
      timestamp: { type: Date, default: Date.now },
      metadata: { type: mongoose.Schema.Types.Mixed, default: {} },
    },
  ],
  evidenceRequests: [
    {
      requestId: { type: String, default: () => `EVR-${Math.floor(1000 + Math.random() * 9000)}` },
      requestedBy: { type: String },
      requestedByName: { type: String },
      note: { type: String, required: true },
      requestedAt: { type: Date, default: Date.now },
      status: { type: String, enum: ['Pending', 'Provided', 'Closed'], default: 'Pending' },
    },
  ],
  officialAlertMatch: {
    matched: { type: Boolean, default: false },
    alertId: { type: String, default: null },
    alertTitle: { type: String, default: '' },
    severity: { type: String, default: '' },
    distanceKm: { type: Number, default: null },
  },
  blockchainTransactionId: {
    type: String,
    default: null,
  },
  blockHash: {
    type: String,
    default: null,
  },
  createdAt: {
    type: Date,
    default: Date.now,
  },
  updatedAt: {
    type: Date,
    default: Date.now,
  },
});

module.exports = mongoose.model('Incident', incidentSchema);
