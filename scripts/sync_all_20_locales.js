function resolvePath(obj, dotPath) {
  return dotPath.split('.').reduce((acc, k) => (acc ? acc[k] : undefined), obj);
}

function setNestedPath(obj, dotPath, value) {
  const parts = dotPath.split('.');
  let curr = obj;
  for (let i = 0; i < parts.length - 1; i++) {
    const p = parts[i];
    if (!curr[p] || typeof curr[p] !== 'object' || Array.isArray(curr[p])) {
      curr[p] = {};
    }
    curr = curr[p];
  }
  curr[parts[parts.length - 1]] = value;
}

function getFlattenedKeys(obj, prefix = '') {
  let keys = [];
  for (const [key, value] of Object.entries(obj)) {
    const fullPath = prefix ? `${prefix}.${key}` : key;
    if (value && typeof value === 'object' && !Array.isArray(value)) {
      keys = keys.concat(getFlattenedKeys(value, fullPath));
    } else {
      keys.push({ path: fullPath, value });
    }
  }
  return keys;
}

function cloneMatchingSchema(sourceTemplate, existingLocale, localeCode) {
  const result = {};
  const overrides = TRANSLATIONS_38[localeCode] || {};

  function traverse(sourceObj, targetObj, prefix = '') {
    for (const [k, v] of Object.entries(sourceObj)) {
      const fullPath = prefix ? `${prefix}.${k}` : k;
      if (v && typeof v === 'object' && !Array.isArray(v)) {
        targetObj[k] = {};
        traverse(v, targetObj[k], fullPath);
      } else {
        // Check if override exists
        if (overrides[fullPath] !== undefined) {
          targetObj[k] = overrides[fullPath];
        } else {
          // Check if existingLocale has this key
          const existingVal = resolvePath(existingLocale, fullPath);
          if (existingVal !== undefined && existingVal !== null && existingVal !== '') {
            targetObj[k] = existingVal;
          } else {
            // If missing, use source template
            targetObj[k] = v;
          }
        }
      }
    }
  }

  traverse(sourceTemplate, result);
  return result;
}

function syncAll() {
  const enRaw = fs.readFileSync(path.join(localesDir, 'en.json'), 'utf8');
  const enJson = JSON.parse(enRaw);
  const canonicalKeys = getFlattenedKeys(enJson);
  const canonicalCount = canonicalKeys.length;

  console.log(`Canonical en.json key count: ${canonicalCount}`);

  const files = fs.readdirSync(localesDir).filter((f) => f.endsWith('.json'));

  for (const f of files) {
    const code = f.replace('.json', '');
    const filePath = path.join(localesDir, f);
    const existing = JSON.parse(fs.readFileSync(filePath, 'utf8'));

    const synchronized = cloneMatchingSchema(enJson, existing, code);
    const syncKeys = getFlattenedKeys(synchronized);

    if (syncKeys.length !== canonicalCount) {
      throw new Error(`Sync mismatch for ${f}: got ${syncKeys.length}, expected ${canonicalCount}`);
    }

    fs.writeFileSync(filePath, JSON.stringify(synchronized, null, 2) + '\n', 'utf8');
    console.log(`✅ Synchronized ${f}: ${syncKeys.length} keys (100% parity)`);
  }
}

